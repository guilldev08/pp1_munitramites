-- Consultas para mirar la base de Munitramites desde VS Code.
-- Extensión: Firebird SQL (wdtbrchan.firebird-vscode).
-- Cursor en una consulta + Ctrl+Enter.
--
-- OJO: tablas y columnas están en MAYÚSCULAS (las creó Django así).

-- 1. Resumen general
SELECT
    (SELECT COUNT(*) FROM MUNITRAMITES_TRAMITE)   AS TRAMITES,
    (SELECT COUNT(*) FROM MUNITRAMITES_REQUISITO) AS REQUISITOS,
    (SELECT COUNT(*) FROM MUNITRAMITES_ORGANISMO) AS ORGANISMOS,
    (SELECT COUNT(*) FROM MUNITRAMITES_TEMA)      AS TEMAS,
    (SELECT COUNT(*) FROM MUNITRAMITES_CONSULTA)  AS CONSULTAS
FROM RDB$DATABASE;

-- 2. Todos los trámites (lo más útil para revisar)
SELECT ID, TITULO, MODALIDAD, ACTIVO, DESTACADO
FROM MUNITRAMITES_TRAMITE
ORDER BY TITULO;

-- 3. Un trámite con su tema, organismo y municipio
SELECT T.ID, T.TITULO, T.MODALIDAD, T.ACTIVO,
       TE.NOMBRE AS TEMA,
       O.NOMBRE  AS ORGANISMO,
       M.NOMBRE  AS MUNICIPIO
FROM MUNITRAMITES_TRAMITE T
LEFT JOIN MUNITRAMITES_TEMA      TE ON TE.ID = T.TEMA_ID
LEFT JOIN MUNITRAMITES_ORGANISMO O  ON O.ID  = T.ORGANISMO_ID
LEFT JOIN MUNITRAMITES_MUNICIPIO M  ON M.ID  = T.MUNICIPIO_ID
ORDER BY T.TITULO;

-- 4. Requisitos de un trámite (cambiá el ID)
SELECT R.ORDEN, R.DESCRIPCION
FROM MUNITRAMITES_REQUISITO R
WHERE R.TRAMITE_ID = 1
ORDER BY R.ORDEN;

-- 5. Trámites por tema
SELECT TE.NOMBRE AS TEMA, COUNT(T.ID) AS TRAMITES
FROM MUNITRAMITES_TEMA TE
LEFT JOIN MUNITRAMITES_TRAMITE T ON T.TEMA_ID = TE.ID
GROUP BY TE.NOMBRE
ORDER BY TRAMITES DESC;

-- 6. Trámites por modalidad
SELECT MODALIDAD, COUNT(*) AS TOTAL
FROM MUNITRAMITES_TRAMITE
GROUP BY MODALIDAD
ORDER BY TOTAL DESC;

-- 7. Últimas consultas de los ciudadanos
SELECT C.ID, C.ASUNTO, C.ESTADO, C.FECHA
FROM MUNITRAMITES_CONSULTA C
ORDER BY C.FECHA DESC
ROWS 20;

-- 8. Conversaciones del chatbot (si hay)
SELECT C.ID, C.TITULO, C.ACTUALIZADO,
       (SELECT COUNT(*) FROM MUNITRAMITES_MENSAJECHAT M
        WHERE M.CONVERSACION_ID = C.ID) AS MENSAJES
FROM MUNITRAMITES_CONVERSACIONCHAT C
ORDER BY C.ACTUALIZADO DESC;

-- 9. Listar todas las tablas de la base
SELECT TRIM(RDB$RELATION_NAME) AS TABLA
FROM RDB$RELATIONS
WHERE RDB$SYSTEM_FLAG = 0 AND RDB$VIEW_BLR IS NULL
ORDER BY 1;

-- 10. Columnas de una tabla (cambiá el nombre)
SELECT TRIM(RDB$FIELD_NAME) AS COLUMNA,
       TRIM(RDB$FIELD_SOURCE) AS TIPO
FROM RDB$RELATION_FIELDS
WHERE RDB$RELATION_NAME = 'MUNITRAMITES_TRAMITE'
ORDER BY RDB$FIELD_POSITION;
